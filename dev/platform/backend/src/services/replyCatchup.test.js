// Standalone tests for the reply catch-up's opt-out reading. Runs with
//   node src/services/replyCatchup.test.js
// and exits non-zero on the first failure. No DB connection is opened — the pg
// Pool is constructed lazily and nothing here queries.
//
// This file exists for one function. unsubPhrase() decides whether a reply
// means "stop emailing me", and the catch-up applies that decision across
// months of backlog in one press. A false negative leaves someone on a list
// they asked to leave; a false positive drops a journalist who was only
// talking about the unsubscribe link. Both are expensive, neither shows up in
// a build.

const assert = require('assert');
const { unsubPhrase, unsubPhraseDetail, isMachineBody, isMachineOptOut } = require('./replyCatchup');

let passed = 0;
function check(name, cond) {
  assert.ok(cond, `FAILED: ${name}`);
  passed++;
}

// ── Plain opt-outs ──────────────────────────────────────────────────────────
check('remove me', unsubPhrase('Please remove me from your list.', 'Re: release') === 'remove me');
check('take me off', unsubPhrase('Take me off this list please.', 'Re: release') === 'take me off');
check('unsubscribe in the body', unsubPhrase('unsubscribe', 'Re: release') === 'unsubscribe');
check('stop sending', unsubPhrase('Please stop sending these.', 'Re: release') === 'stop sending');
check('no longer wish to receive',
  unsubPhrase('I no longer wish to receive these emails.', 'Re: release') === 'no longer wish to receive');
// When several phrases match, the one reported is whichever comes first in
// UNSUB_PHRASES. That is an arbitrary but stable choice, and what matters to
// the caller is that an opt-out was detected at all, so assert that.
check('not my beat, worded as removal, is detected',
  unsubPhrase('Not my beat — please remove from the list.', 'Re: x') !== null);

// ── The One-Click case ──────────────────────────────────────────────────────
// A mail client acting on List-Unsubscribe sends "unsubscribe" as the SUBJECT
// with an empty body. Reading only the body missed every one of those, which is
// how a journalist who pressed Unsubscribe in Gmail carried on being emailed.
check('subject-only opt-out', unsubPhrase('', 'unsubscribe') === 'unsubscribe');
check('subject-only with an empty body and no match elsewhere',
  unsubPhrase('   ', 'Unsubscribe') === 'unsubscribe');

// ── Not opt-outs ────────────────────────────────────────────────────────────
check('an interested reply is not an opt-out',
  unsubPhrase('Great, send me the images at print resolution.', 'Re: release') === null);
check('a question is not an opt-out',
  unsubPhrase('What is the embargo on this?', 'Re: release') === null);
check('empty is not an opt-out', unsubPhrase('', '') === null);

// ── Our own quoted footer ───────────────────────────────────────────────────
// Every reply carries a copy of the mail it answers, and ours ends with an
// unsubscribe line. Matching the whole body would mark every single reply as an
// opt-out, including "yes please".
const quoted = [
  'Yes please, send them over.',
  '',
  'On Mon, 12 Oct 2026, October Communications wrote:',
  '> Hotels spend seven figures on design, then hang stock art.',
  "> If this isn't relevant to your beat, no hard feelings — unsubscribe here.",
  '> To be removed from the list, click unsubscribe.',
].join('\n');
check('a quoted footer below a positive reply is ignored', unsubPhrase(quoted, 'Re: release') === null);

const quotedDash = [
  'Happy to take a look.',
  '-----Original Message-----',
  'From: October Communications',
  'Please remove from your list if this is not relevant.',
].join('\n');
check('an Outlook-style quote block is ignored', unsubPhrase(quotedDash, 'Re: release') === null);

// A real opt-out ABOVE a quoted footer must still be caught — the quote
// stripping must not swallow the message.
const realAboveQuote = [
  'Please take me off this list.',
  '',
  'On Mon, October Communications wrote:',
  '> the release text',
].join('\n');
check('a genuine opt-out above a quote is still caught',
  unsubPhrase(realAboveQuote, 'Re: release') === 'take me off');

// ── Case and spacing ────────────────────────────────────────────────────────
check('case-insensitive', unsubPhrase('PLEASE REMOVE ME.', 'Re: x') === 'remove me');
check('hyphenated opt-out', unsubPhrase('I want to opt-out.', 'Re: x') === 'opt-out');

// ── A One-Click opt-out is not a reply ──────────────────────────────────────
// Gmail's List-Unsubscribe One-Click sends a mail whose subject is
// "unsubscribe" (OMI's own header asks for that) and whose body is boilerplate.
// It must be actioned as an opt-out and must NOT be counted as a reply: the
// first live scan found these behind 8 open sends each, and marking them
// replied would have inflated the reply rate with machine traffic.
const GMAIL_ONE_CLICK = 'This message was automatically generated by Gmail.';
check('One-Click is detected as a machine opt-out',
  isMachineOptOut(GMAIL_ONE_CLICK, 'unsubscribe') === true);
check('One-Click with an empty body is too',
  isMachineOptOut('', 'unsubscribe') === true);
check('it is still an opt-out', unsubPhrase(GMAIL_ONE_CLICK, 'unsubscribe') === 'unsubscribe');

check('a person who typed "unsubscribe" in the body is NOT a machine opt-out',
  isMachineOptOut('unsubscribe', 'Re: release') === false);
check('a person writing a sentence is not a machine opt-out',
  isMachineOptOut('Please take me off this list, it is not my beat.', 'Re: release') === false);
check('a long body under an unsubscribe subject is not machine boilerplate',
  isMachineOptOut('unsubscribe '.repeat(40), 'unsubscribe') === false);

check('where: subject is reported',
  unsubPhraseDetail('', 'unsubscribe').where === 'subject');
check('where: body is reported',
  unsubPhraseDetail('please remove me', 'Re: x').where === 'body');

check('an empty body counts as machine-written', isMachineBody('') === true);
check('provider boilerplate counts', isMachineBody('This message was auto-generated by Outlook') === true);
check('a real sentence does not', isMachineBody('Thanks, please remove me from the list.') === false);

// ---------------------------------------------------------------------------
// Structural guards on the SQL, which no pure-function test can reach.
//
// A re-scan refreshes rows that are still pending, so a reader improvement
// (MIME decoding, say) reaches proposals an earlier scan already raised. The
// guard that keeps that safe is the WHERE: an applied row has already written
// to sends and contacts, and a dismissed row is a decision. Overwriting either
// from a re-read of the mailbox would be rewriting history.
const src = require('fs').readFileSync(require('path').join(__dirname, 'replyCatchup.js'), 'utf8');

check('the re-scan upsert exists', /ON CONFLICT \(message_key\) DO UPDATE/.test(src));
check('and it only ever touches pending rows',
  /DO UPDATE[\s\S]{0,900}?WHERE outreach_reply_catchup\.status = 'pending'/.test(src));
check('a decided row is left alone before any recompute',
  /seen\[0\]\.status !== 'pending'\) return 'seen'/.test(src));
check('the body is read through the MIME reader, not a blank-line split',
  /mimeText\.bodyText\(msg\.source \|\| raw\)/.test(src));
check('nothing still reaches for the old whole-body text',
  !/oooMailScan\.toText\(/.test(src));

// ---------------------------------------------------------------------------
// The review screen tells you, per row, what Apply will do: which list someone
// comes off, and how many queued emails stop. Those sentences are only honest
// while the numbers behind them are real, so the contract is guarded here.
//
// The two scopes are the whole point and are easy to collapse into one by
// accident: marking a reply cancels pending sends to the contact ANYWHERE,
// while an opt-out cancels them for ONE client. A notice built on a single
// count would be wrong for one of the two every time.
check('the scan counts pending sends in both scopes',
  /COUNT\(\*\)::int AS all_clients[\s\S]{0,200}?FILTER \(WHERE c\.client_id = \$2\)::int AS this_client/.test(src));
check('it counts only what is still queued',
  /AS this_client[\s\S]{0,200}?s\.status = 'pending'/.test(src));
check('both counts are stored on the row',
  /pending_all, pending_client, counts_known/.test(src));
check('and refreshed when a pending row is re-read',
  /DO UPDATE[\s\S]{0,900}?pending_all\s+= EXCLUDED\.pending_all[\s\S]{0,200}?pending_client = EXCLUDED\.pending_client/.test(src));
check('counts_known is set, so a row never implies zero when nothing was counted',
  /counts_known\s+= TRUE/.test(src));

console.log(`replyCatchup: ${passed} checks passed (including SQL guards).`);
